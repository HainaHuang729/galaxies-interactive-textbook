// Migrate legacy literal paints to shared tokens. Numerical model code is untouched.
// Re-running preserves existing wrappers, and collects their original fallback colors.
const fs = require('node:fs'), path = require('node:path');
const assets = path.resolve(__dirname, '../dist/assets');
const palettes = {
  afterglow: { bg:'#10151c', panel:'#1a222d', subtle:'#151c25', soft:'#242e3b', text:'#f1ece2', muted:'#b6b5b1', line:'#3a434d', gold:'#e5bf83', cyan:'#84bcd5', third:'#b0b9e0', hot:'#d7a2b4', out:'#a5acc1', on:'#272013', hover:'#f1cfa0' },
  moon: { bg:'#edf0f7', panel:'#fafbff', subtle:'#e7ebf4', soft:'#e0e6f1', text:'#19263f', muted:'#5d6c87', line:'#cbd3e3', gold:'#6c4fb0', cyan:'#287e92', third:'#435cb1', hot:'#a2456c', out:'#606f90', on:'#ffffff', hover:'#354a96' }
};
const explicit = {
  '0b141b':'bg','070f18':'bg','09131b':'subtle','13212a':'panel','0e1a22':'panel',
  '101d25':'panel','14232b':'panel','11222a':'subtle','293c45':'line','29414a':'line',
  '435962':'line','2d424b':'line','273b43':'line','3e555e':'line','45675e':'line',
  'e7efed':'text','c8d5d4':'text','98aeae':'muted','b5cebb':'third','bfc8bf':'third',
  'e4c389':'gold','f1ce8c':'gold','7abdc4':'cyan','63aebd':'cyan','b78d9b':'hot','8e9daa':'out',
  '14251b':'on','132019':'on','c9dfce':'hover','bbcecb':'muted','59727a':'line'
};
function expand(hex) {
  const h = hex.slice(1).toLowerCase();
  return h.length < 5 ? [...h].map(c=>c+c).join('') : h;
}
function role(hex) {
  if (explicit[hex]) return explicit[hex];
  const [r,g,b]=[0,2,4].map(i=>parseInt(hex.slice(i,i+2),16));
  const max=Math.max(r,g,b),min=Math.min(r,g,b),brightness=.2126*r+.7152*g+.0722*b;
  if(max<50) return brightness<19?'bg':'panel';
  if(max<85) return 'soft';
  if(brightness<100) return 'line';
  if(max-min<32) return brightness>218?'text':'muted';
  if(r>g*1.06&&g>b*1.04) return 'gold';
  if(r>g*1.07&&b>g) return 'hot';
  if(g>r&&g>b) return 'third';
  if(b>r*1.07||g>r*1.08) return 'cyan';
  return brightness>200?'text':'muted';
}
const paints=new Set();
const hexPattern=/#[\da-f]{8}\b|#[\da-f]{6}\b|#[\da-f]{4}\b|#[\da-f]{3}\b/gi;
const cssFiles=fs.readdirSync(assets).filter(n=>n.endsWith('.css')&&!['anatomy-iso.css','rotation.css','book-theme.css','theme-tokens.css'].includes(n));
for(const name of cssFiles) {
  const file=path.join(assets,name),text=fs.readFileSync(file,'utf8');
  for(const h of text.match(hexPattern)||[])paints.add(h.toLowerCase());
  const updated=text.replace(/var\(--legacy-[\da-f]+,#[\da-f]+\)|#[\da-f]{8}\b|#[\da-f]{6}\b|#[\da-f]{4}\b|#[\da-f]{3}\b/gi, h=>h.startsWith('var(')?h:`var(--legacy-${h.slice(1).toLowerCase()},${h})`);
  fs.writeFileSync(file,updated);
}
const jsFiles=['chapter-one','chapter-two','chapter-three','chapter-four','chapter-five','chapter-six','chapter-seven','chapter-eight','advanced-book','review-enhancements'];
for(const name of jsFiles) {
  const file=path.join(assets,name+'.js');let text=fs.readFileSync(file,'utf8');
  for(const h of text.match(hexPattern)||[])paints.add(h.toLowerCase());
  const held=[];
  const hold=value=>{held.push(value);return `__BOOK_PAINT_HOLD_${held.length-1}__`;};
  // Live palette objects must keep their original strings, not cache an initial theme.
  text=text.replace(/window\.BookTheme\.palette\((\{[^{}]*\}|\[[^\[\]]*\])\)/g,hold);
  text=text.replace(/\b(C|colors)=(\{[^{}]*\}|\[[^\[\]]*\])/g,(all,name,value)=>value.includes('#')?`${name}=${hold(`window.BookTheme.palette(${value})`)}`:all);
  // Astronomical image rendering keeps its fixed dark exposure and stellar hues.
  if(name==='chapter-one')text=text.replace(/function drawGalaxy\(\)[\s\S]*?(?=function resizeGalaxy)/,hold);
  text=text.replace(/window\.BookTheme\.color\(['"]#[\da-f]+['"]\)|(['"])(#[\da-f]{3,8})\1/gi,(all,quote,hex)=>hex?`window.BookTheme.color('${hex.toLowerCase()}')`:all);
  text=text.replace(/__BOOK_PAINT_HOLD_(\d+)__/g,(_,i)=>held[+i]);
  fs.writeFileSync(file,text);
}
let css='/* Generated by scripts/build-theme-tokens.cjs; keep source-color fallbacks in renderers. */\n';
for(const [theme,palette]of Object.entries(palettes)) {
  css+=(theme==='afterglow'?':root':':root[data-book-theme="moon"]')+' {\n';
  for(const hex of [...paints].sort()) {
    const expanded=expand(hex),base=expanded.slice(0,6),alpha=expanded.slice(6);
    css+=`  --legacy-${hex.slice(1)}: ${palette[role(base)]}${alpha};\n`;
  }
  css+='}\n';
}
fs.writeFileSync(path.join(assets,'theme-tokens.css'),css);
console.log(`Installed ${paints.size} shared paints for CSS, SVG and canvas.`);
